// The token radar's model, version radar-2.
//
// The board ranks pre-token protocols by an implied value the snapshot itself
// prices. The house starter multiplies every protocol's TVL by one flat 0.25;
// this model instead asks the market: for each category, it takes the median
// market-cap-to-TVL ratio of the snapshot's own live-token protocols in that
// category (falling back to the global median), and uses that as the category's
// multiple. A lending protocol and a bridge are therefore priced like lending
// protocols and bridges actually trade, not like each other.
//
//   multiple     = median live mcap/TVL in the protocol's category (clamped)
//   growth       = exp(0.30 * tanh(change_7d / 40))   — smooth, bounded
//   maturity     = 0.55 + 0.45 * (1 - exp(-age_days / 540))
//   staleness    = 0.90 when age > 900 days and 7d change is negative, else 1
//   chains       = 1 + 0.04 * min(chains - 1, 5)
//   implied      = max(1, round(tvl * multiple * growth * maturity * staleness * chains))
//
// Age is days from listed_at to the snapshot's as_of; unknown age counts as
// 365 days. No protocol name is ever special-cased: the same function scores
// every row, and the multiples come from the snapshot, never from a list.
//
// The board covers every watchlist slug, then adds pre-token protocols the
// watchlist leaves out, under the watchlist's own exclusion rules (no CEX,
// no bridge or staking products, no versioned pools, no wrapped/staked
// names, no exchange-branded names). Live-token protocols are never ranked;
// the dashboard shows the top ones by market cap as the calibration source.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

